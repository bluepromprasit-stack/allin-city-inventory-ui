#!/usr/bin/env node
// All In City: generate src/generated/item-categories.json (item name -> theme category, bound flag) from the theme
// item table resources/[theme]/theme_data/data/items.json of the All In City monorepo.
//
// ox_inventory items carry no category (client.lua:1235-1244 builds the UI item data field by field), so the forked UI
// resolves a category in this order (src/dt/categories.ts): Items[name].category (if a future Lua patch forwards one)
// -> this generated map -> the stock-item map -> name prefix (WEAPON_ / ammo- / at_) -> "other".
// The output is COMMITTED so the fork builds on its own (public source mirror without theme_data).
//
//   node scripts/gen-categories.mjs            # rewrite the JSON
//   node scripts/gen-categories.mjs --check    # exit 1 if the committed JSON is stale (wired into npm run ci)
//   node scripts/gen-categories.mjs --source <items.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../src/generated/item-categories.json');
const args = process.argv.slice(2);
const check = args.includes('--check');
const srcAt = args.indexOf('--source');
const SOURCE =
  srcAt >= 0 ? path.resolve(args[srcAt + 1]) : path.resolve(HERE, '../../../../resources/[theme]/theme_data/data/items.json');

if (!fs.existsSync(SOURCE)) {
  console.error(`gen-categories: source not found: ${SOURCE}`);
  process.exit(2);
}

const table = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const list = Array.isArray(table) ? table : table.items;
if (!Array.isArray(list)) {
  console.error('gen-categories: expected { items: [...] } in the source');
  process.exit(2);
}

const items = {};
for (const item of [...list].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
  if (typeof item.name !== 'string' || typeof item.category !== 'string') {
    console.error(`gen-categories: item without name/category: ${JSON.stringify(item).slice(0, 120)}`);
    process.exit(2);
  }
  items[item.name] = item.bound === true ? { category: item.category, bound: true } : { category: item.category };
}

const json = `${JSON.stringify(
  {
    $comment:
      'GENERATED by scripts/gen-categories.mjs from resources/[theme]/theme_data/data/items.json (All In City) - do not edit by hand',
    items,
  },
  null,
  2
)}\n`;

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== json) {
    console.error('gen-categories: src/generated/item-categories.json is stale - run node scripts/gen-categories.mjs');
    process.exit(1);
  }
  console.log(`gen-categories: ${Object.keys(items).length} items, generated map is current`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, json);
  console.log(`gen-categories: wrote ${path.relative(process.cwd(), OUT)} (${Object.keys(items).length} items)`);
}
